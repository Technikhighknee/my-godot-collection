// Content-addressed project build planning. This module never renders assets,
// mutates project sources, or decides how a generator is implemented.
import {createHash} from 'node:crypto';
import type {AssetEntry,ProjectAssetSource} from './library.ts';

const digest=(value:string)=>createHash('sha256').update(value).digest('hex');
function canonical(value:unknown):unknown{
  if(Array.isArray(value))return value.map(canonical);
  if(value&&typeof value==='object')
    return Object.fromEntries(Object.entries(value).sort(([a],[b])=>
      a<b?-1:a>b?1:0).map(([k,v])=>[k,canonical(v)]));
  return value;
}
// Output format versions are independent of saved generator recipe versions.
// Changing an exporter must invalidate its cache without rewriting sources.
const OUTPUT_FORMAT_VERSIONS={model:2,image:1} as const;
function sourceIdentity(source:ProjectAssetSource,kind:'model'|'image'):unknown{
  // Names are UI labels and do not affect generated bytes.
  // Dependencies themselves are included through their transitive keys.
  if('origin' in source)
    return {origin:'imported',kind:source.kind,format:source.imported.format,
      sha256:source.imported.sha256};
  // Master seed is only an editing convenience. The registry generates
  // from resolved component seeds, so master-only changes cannot alter bytes.
  const {id,version,components}=source.generator;
  return {origin:'procedural',generator:{id,version,components},
    output:{kind,version:OUTPUT_FORMAT_VERSIONS[kind]},
    options:source.options??null,materials:source.materials??null};
}
export interface BuildNode {
  id:string;kind:'model'|'image';origin:'procedural'|'imported';
  sourceRevision:string;key:string;dependencies:string[];
}
export interface BuildPlan {
  format:'devtool-build-plan';version:1;
  roots:string[];key:string;nodes:BuildNode[];
}
export function planAssetBuild(entries:readonly AssetEntry[],
  only?:readonly string[]):BuildPlan{
  const byId=new Map<string,AssetEntry>();
  for(const entry of entries){
    const id=entry.source.id;
    if(byId.has(id))throw Error('Duplicate project asset ID: '+id);
    byId.set(id,entry);
  }
  const roots=[...new Set(only??[...byId.keys()])].sort();
  if(!roots.length)throw Error('No assets available to build');
  const visited=new Map<string,BuildNode>(),active=new Set<string>();
  const ordered:BuildNode[]=[];
  function resolve(id:string):BuildNode{
    const existing=visited.get(id);
    if(existing)return existing;
    if(active.has(id))throw Error('Asset dependency cycle: '+id);
    const entry=byId.get(id);
    if(!entry)throw Error('Missing asset dependency: asset:'+id);
    active.add(id);
    const dependencies=entry.source.dependencies.map(ref=>{
      if(!ref.startsWith('asset:'))throw Error('Invalid asset dependency: '+ref);
      return ref.slice('asset:'.length);
    }).sort();
    const child=dependencies.map(resolve);
    const key=digest(JSON.stringify(canonical({
      schema:1,id,source:sourceIdentity(entry.source,entry.kind),
      dependencies:child.map(d=>({id:d.id,key:d.key})),
    })));
    const node:BuildNode={id,kind:entry.kind,
      origin:'origin' in entry.source?'imported':'procedural',
      sourceRevision:entry.revision,key,dependencies};
    active.delete(id);visited.set(id,node);ordered.push(node);
    return node;
  }
  const chosen=roots.map(resolve);
  return {format:'devtool-build-plan',version:1,roots,
    key:digest(JSON.stringify(chosen.map(node=>({id:node.id,key:node.key})))),
    nodes:ordered};
}
